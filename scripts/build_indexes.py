#!/usr/bin/env python3
"""Generate every index page from the registers.

Nothing in this repository lists a publication because somebody typed it into an index.
Indexes are derived from `registers/publications.json`, which means a library index can
never advertise a title that does not resolve, and a document can never be published by
being dropped into a directory.

The register lists nineteen identifiers and the corpus ships six. That gap is rendered
honestly: the library shows what exists, the roadmap names what is registered and not
drafted, and no page presents a count of publications as an achievement.

    python3 scripts/build_indexes.py            write the generated indexes
    python3 scripts/build_indexes.py --check    fail if what is on disk differs

`--check` is what CI runs. A generated file committed by hand, or a register edited
without regenerating, fails the build rather than shipping a stale index.
"""

from __future__ import annotations

import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REG = os.path.join(ROOT, "registers")
OUT = os.path.join(ROOT, "registers", "_generated")

CATEGORY = {
    "papers": ("Research papers", "R",
               "Long-form argument. Each paper states a position, classes every material "
               "statement, and names the conditions under which it would be wrong."),
    "institutional": ("Institutional publications", "P",
                      "What the Program is doing and how it reports on itself."),
    "technical-notes": ("Technical notes", "TN",
                        "A single problem, treated directly."),
}

BANNER = "<!-- GENERATED by scripts/build_indexes.py. Do not edit. -->"


def load(name):
    return json.load(open(os.path.join(REG, name), encoding="utf-8"))


def render_library(pubs, caps) -> str:
    live = [e for e in pubs["entries"] if e["publish"] and e["content_present"]]
    held = [e for e in pubs["entries"] if not e["publish"]]
    out = [BANNER, "", "# Research", "",
           "The public research corpus of the NEO AI Research Program.", "",
           "Every material statement carries a claim class. `[E]` established, with an "
           "external primary source. `[A]` architectural interpretation. `[D]` design "
           "intent, carrying a capability status. `[O]` open problem.", "",
           "Capability statuses resolve from the Capability Register, which is version "
           f"{caps['version']} and is Founder-ratified as the approved public maturity "
           "classification. Register ratification does not mean that every capability "
           "is deployed or individually ratified. Nothing here describes a deployed "
           "system unless its S-status says so.", ""]
    for cat, (title, code, blurb) in CATEGORY.items():
        rows = [e for e in live if e["category_slug"] == cat]
        out += [f"## {title}", "", blurb, ""]
        if not rows:
            out += ["Nothing published in this category yet.", ""]
            continue
        out += ["| Identifier | Title |", "|---|---|"]
        for e in rows:
            ident = e["id"] if e["identifier_allocated"] else "Not yet allocated"
            out.append(f"| {ident} | [{e['title']}]({e['canonical_url']}) |")
        out.append("")
    if held:
        out += ["## Prepared and not yet published", "",
                "Public editions of existing research, held for the next wave. Each is a "
                "reduction of a longer internal document, never a paraphrase of a "
                "withheld passage.", "",
                "| Title | State |", "|---|---|"]
        for e in held:
            out.append(f"| {e['title']} | Held for Wave {e['wave']} |")
        out.append("")
    out += ["## Registered and not drafted", "",
            "These identifiers exist so that the library does not appear to have gaps it "
            "cannot explain. **No date is attached to any of them.** A research "
            "destination that lists more than it delivers has made a claim it cannot "
            "support.", "",
            "| Identifier | Title |", "|---|---|"]
    for n in pubs["registered_not_drafted"]:
        out.append(f"| {n['id']} | {n['title']} |")
    out.append("")
    return "\n".join(out)


def render_category(pubs, cat) -> str:
    title, code, blurb = CATEGORY[cat]
    rows = [e for e in pubs["entries"]
            if e["category_slug"] == cat and e["publish"] and e["content_present"]]
    out = [BANNER, "", f"# {title}", "", blurb, ""]
    if not rows:
        out += ["Nothing published in this category yet. The category page exists so "
                "that a link to it never breaks, and it lists nothing rather than "
                "listing something that does not resolve.", ""]
        return "\n".join(out)
    out += ["| Identifier | Title | Version |", "|---|---|---|"]
    for e in rows:
        ident = e["id"] if e["identifier_allocated"] else "Not yet allocated"
        out.append(f"| {ident} | [{e['title']}]({e['canonical_url']}) | "
                   f"{e.get('version', 'v1.0')} |")
    out.append("")
    return "\n".join(out)


def render_roadmap(pubs) -> str:
    out = [BANNER, "", "# Roadmap", "",
           "What is registered and not drafted. **No dates.** A roadmap with dates on it "
           "is a commitment, and the Program does not make one here.", "",
           "| Identifier | Title | Note |", "|---|---|---|"]
    for n in pubs["registered_not_drafted"]:
        out.append(f"| {n['id']} | {n['title']} | {n.get('note', '')} |")
    out += ["", "A registered identifier means the subject is claimed within the corpus "
                "numbering. It means nothing else. It does not mean drafting has begun.",
            ""]
    return "\n".join(out)


def render_ledger(caps) -> str:
    state = caps.get("platformState", {})
    out = [BANNER, "", "# Capability Register", "",
           f"Register version {caps['version']}. **{caps['status']}**", ""]
    if state:
        out += ["## State of the platform", "", state["summary"], "",
                f"Classification: {state['classification']}. "
                f"{state['independentVerification']}", ""]
    out += [
           "Every capability NEO AI describes, with its status. A page that describes a "
           "capability links to its row here, and the status rendered on that page is "
           "resolved from this register at build time rather than written by an author.",
           "", "| Status | Meaning |", "|---|---|"]
    for k in sorted(caps["statusDefinitions"]):
        out.append(f"| {k} | {caps['statusDefinitions'][k]} |")
    out += ["", "| Key | Capability | Status | Note |", "|---|---|---|---|"]
    for c in caps["capabilities"]:
        out.append(f"| `{c['key']}` | {c['name']} | **{c['status']}** | "
                   f"{c.get('note', '')} |")
    if caps.get("retired"):
        out += ["", "## Retired keys", "",
                "A retired key resolves to its successor. It is never reissued.", "",
                "| Retired key | Successor | Reason |", "|---|---|---|"]
        for r in caps["retired"]:
            out.append(f"| `{r['key']}` | `{r['successor']}` | {r['reason']} |")
    counts = {}
    for c in caps["capabilities"]:
        counts[c["status"]] = counts.get(c["status"], 0) + 1
    out += ["", "## Distribution", "",
            "Counted from the register, not asserted.", "",
            "| Status | Count |", "|---|---|"]
    for k in sorted(counts):
        out.append(f"| {k} | {counts[k]} |")
    out += ["", f"Total: {len(caps['capabilities'])}.", ""]
    return "\n".join(out)


def render_glossary_index(voc) -> str:
    out = [BANNER, "", "# Glossary", "",
           "The controlled vocabulary of the corpus. A term in this list is used exactly "
           "as written, everywhere, and the first occurrence of a term on any page links "
           "here.", "",
           f"{voc['count_before_amendment']} locked terms. "
           f"{voc['terms_added']} added by amendment. "
           f"{voc['count_after_amendment']} in total.", "",
           "## Locked terms", ""]
    out += [f"- {t}" for t in voc["locked_terms"]]
    out += ["", "## Added by amendment", ""]
    out += [f"- {t}" for t in voc["added_terms"]]
    out += ["", "## Prohibited synonyms", "",
            "These are not neutral alternatives. Each was considered and refused.", "",
            "| Prohibited | Use instead |", "|---|---|"]
    smap = voc.get("prohibited_synonym_map", {})
    for t in voc["prohibited_synonyms"]:
        use = smap.get(t, {}).get("use", "Provider Replaceability")
        out.append(f"| {t} | {use} |")
    out += ["", voc["prohibited_synonym_note"], ""]
    for t in voc["prohibited_synonyms"]:
        if smap.get(t, {}).get("note"):
            out.append(f"- **{t}.** {smap[t]['note']}")
    out.append("")
    for r in voc.get("renamed_terms", []):
        out.append(f"Renamed in vocabulary {r['version']}: {r['from']} is now {r['to']}.")
    out.append("")
    return "\n".join(out)


def main() -> int:
    check = "--check" in sys.argv[1:]
    pubs, caps, voc = (load("publications.json"), load("capabilities.json"),
                       load("vocabulary.json"))

    files = {
        "library.md": render_library(pubs, caps),
        "roadmap.md": render_roadmap(pubs),
        "capability-register.md": render_ledger(caps),
        "glossary-index.md": render_glossary_index(voc),
    }
    for cat in CATEGORY:
        files[f"index-{cat}.md"] = render_category(pubs, cat)

    os.makedirs(OUT, exist_ok=True)
    drift = []
    for name, body in files.items():
        p = os.path.join(OUT, name)
        current = open(p, encoding="utf-8").read() if os.path.exists(p) else None
        if current != body:
            drift.append(name)
            if not check:
                open(p, "w", encoding="utf-8").write(body)

    if check:
        if drift:
            print("build_indexes --check: these generated files are stale or hand edited:")
            for d in drift:
                print("  registers/_generated/" + d)
            print("Run: python3 scripts/build_indexes.py")
            return 1
        print(f"build_indexes --check: {len(files)} generated files are current.")
        return 0

    print(f"build_indexes: wrote {len(files)} files to registers/_generated/ "
          f"({len(drift)} changed).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
